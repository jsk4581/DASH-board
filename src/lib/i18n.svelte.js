/** Translate `key` for the current language, interpolating {name} vars. */
export function t(key, vars) {
  const table = dict[ui.lang] ?? dict.ko
  let s = table[key] ?? dict.ko[key] ?? key
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, vars[k])
  return s
}
